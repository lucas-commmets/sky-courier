create or replace function public.submit_score(
  p_name text,
  p_score integer,
  p_difficulty text
)
returns boolean
language plpgsql
-- Record every run and update the signed-in player's best for that difficulty.
security definer
set search_path = ''
as $$
declare
  clean_name text;
  clean_difficulty text;
  submitting_user uuid;
  previous_best integer;
  is_new_best boolean;
begin
  clean_name := left(btrim(p_name), 12);
  clean_difficulty := lower(btrim(p_difficulty));
  submitting_user := auth.uid();
  if clean_name is null
    or char_length(clean_name) = 0
    or clean_name ~ '[[:cntrl:]]'
    or p_score is null
    or p_score < 0
    or p_score > 1000000
    or clean_difficulty is null
    or clean_difficulty not in ('easy', 'normal', 'hard') then
    raise exception 'Invalid leaderboard entry';
  end if;
  if submitting_user is null then
    raise exception 'Sign in is required to submit a score';
  end if;

  select score into previous_best
    from public.leaderboard
    where user_id = submitting_user and difficulty = clean_difficulty;
  if not found then
    previous_best := -1;
  end if;
  is_new_best := p_score > previous_best;

  insert into public.score_attempts (user_id, player_name, score, difficulty)
    values (submitting_user, clean_name, p_score, clean_difficulty);

  insert into public.leaderboard (player_name, score, difficulty, user_id)
    values (clean_name, p_score, clean_difficulty, submitting_user)
  on conflict (user_id, difficulty) where user_id is not null do update
    set player_name = case
          when excluded.score > leaderboard.score then excluded.player_name
          else leaderboard.player_name
        end,
        score = greatest(leaderboard.score, excluded.score),
        updated_at = case
          when excluded.score > leaderboard.score then now()
          else leaderboard.updated_at
        end;

  return is_new_best;
end;
$$;

revoke all on function public.submit_score(text, integer, text) from public;
grant execute on function public.submit_score(text, integer, text) to authenticated;
